import os
import json
from typing import Optional
from fastapi import FastAPI, UploadFile, File, HTTPException, Query
from fastapi.responses import FileResponse
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel
import uvicorn

try:
    from google import genai
except ImportError:
    genai = None

from analytics import ConfigAnalyticsEngine

app = FastAPI(title="ConfigIntel Observability API", version="1.0.0")

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

# Initialize engine with default datasets if available on disk
engine = ConfigAnalyticsEngine(
    csv_path="execution_data_master.csv", 
    jsonl_path="system_execution_logs.jsonl"
)

class ChatRequest(BaseModel):
    query: str = ""
    gemini_key: str = ""
    mode: str = "Gemini"

@app.get("/api/health")
async def health_check():
    """Health and status endpoint for frontend connection verification."""
    return {
        "status": "healthy",
        "data_loaded": not engine.df.empty,
        "total_runs": len(engine.df) if not engine.df.empty else 0,
        "columns": list(engine.df.columns)[:15] if not engine.df.empty else []
    }

@app.post("/api/ingest")
async def ingest_data(csv_file: UploadFile = File(...), jsonl_file: Optional[UploadFile] = File(None)):
    """Ingests fresh CSV telemetry and optional JSONL trace logs."""
    try:
        jsonl_lines = None
        if jsonl_file and jsonl_file.filename:
            content = await jsonl_file.read()
            jsonl_lines = content.splitlines()
            
        csv_file.file.seek(0)
        engine.update_from_memory(csv_file.file, jsonl_lines)
        return {
            "status": "success", 
            "total_runs": len(engine.df),
            "message": f"Successfully ingested {len(engine.df):,} execution runs."
        }
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Ingestion failed: {str(e)}")

