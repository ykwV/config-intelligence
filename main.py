@app.get("/api/run/{run_id}")
async def get_single_run(run_id: str):
    """Returns details and full trace events for a specific run ID."""
    details, logs = engine.get_run_details(run_id)
    if not details:
        raise HTTPException(status_code=404, detail=f"Run {run_id} not found.")
    return {"run_id": run_id, "details": details, "events": logs}

@app.get("/api/diff")
async def get_diff(pass_id: str, fail_id: str):
    """Calculates configuration and trace log diff between passing and failing executions."""
    if engine.df.empty:
        raise HTTPException(status_code=400, detail="No dataset loaded in engine.")
    params, log_p, log_f = engine.compute_run_diff(pass_id, fail_id, as_df=False)
    return {"params": params, "log_p": log_p, "log_f": log_f}

